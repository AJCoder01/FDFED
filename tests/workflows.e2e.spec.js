import {test,expect} from '@playwright/test';
import {login,navigate} from './helpers';
const future = (days=14)=>new Date(Date.now()+days*86400000).toISOString().slice(0,10);
async function fillIdentity(page,name,email){
  await page.getByLabel('Full Name').fill(name);
  await page.getByLabel('Email Address').fill(email);
  await page.getByRole('textbox',{name:/Phone Number/}).fill('9876543210');
  await page.locator('input[type=password]').nth(0).fill('123456Ab@');
  await page.locator('input[type=password]').nth(1).fill('123456Ab@');
}
test('mobile navigation, focus, notifications and theme work for every role',async({page})=>{
  test.setTimeout(90000);
  await page.setViewportSize({width:320,height:800});
  for(const role of ['customer','provider','admin','arbitrator']){
    await login(page,role);
    const toggle=page.getByRole('button',{name:'Open navigation'});
    await toggle.click();
    const dialog=page.getByRole('dialog',{name:'Navigation'});
    await expect(dialog).toBeVisible();
    await page.keyboard.press('Shift+Tab');
    expect(await dialog.evaluate(el=>el.contains(document.activeElement))).toBe(true);
    await page.keyboard.press('Escape');
    await expect(toggle).toBeFocused();
    await toggle.click();
    await dialog.getByRole('link',{name:'Profile',exact:true}).click();
    await expect(dialog).not.toBeVisible();
    await expect(page).toHaveURL(new RegExp(`/${role}/profile`));
    const bell=page.getByRole('button',{name:/Open notifications/});
    await bell.click();
    await expect(page.getByRole('dialog',{name:'Notifications'})).toBeVisible();
    await page.keyboard.press('Escape');await expect(bell).toBeFocused();
    await page.getByRole('button',{name:'Switch to dark theme'}).click();
    await page.reload();await expect(page.locator('html')).toHaveAttribute('data-theme','dark');
    await page.getByRole('button',{name:'Switch to light theme'}).click();
    expect(await page.evaluate(()=>document.documentElement.scrollWidth)).toBeLessThanOrEqual(320);
    await page.getByRole('button',{name:'Log out',exact:true}).click();
    await expect(page).toHaveURL('/');
  }
});
