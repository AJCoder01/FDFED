test('provider creates a listing on mobile and staff can pause its public visibility', async ({ page }) => {
  await page.setViewportSize({ width: 320, height: 800 });
  await login(page, 'provider');
  await navigate(page, '/provider/services/new');
  await page.getByLabel('Service Title').fill('Browser QA Inspection');
  await page.getByLabel('Service Category').selectOption('cat-1');
  await page.getByLabel('Fixed Price (INR)').fill('450');
  await page.getByLabel('Duration (Minutes)').fill('60');
  await page.getByLabel('Detailed Description').fill('A careful home inspection with a written service report.');
  await page.getByLabel('Slot Start Time').fill('10:00');
  await page.getByRole('button', { name: 'Add Slot', exact: true }).click();
  const created = page.waitForResponse(response => response.url().endsWith('/api/v1/services') && response.request().method() === 'POST');
  await page.getByRole('button', { name: 'Save & Publish', exact: true }).click();
  const response = await created;
  expect(response.status()).toBe(201);
  const listing = await response.json();
  await expect(page.getByRole('dialog')).not.toBeVisible();
  await page.goto(`/services/${listing.id}`);
  await expect(page.getByRole('heading', { name: 'Browser QA Inspection' })).toBeVisible();
  await login(page, 'admin');
  await navigate(page, '/admin/services');
  const row = page.getByRole('row').filter({ hasText: 'Browser QA Inspection' });
  await row.getByRole('button', { name: 'Pause', exact: true }).click();
  await expect(row.getByText('paused', { exact: true })).toBeVisible();
  await page.getByRole('button', { name: 'Log out', exact: true }).click();
  await expect(page).toHaveURL('/');
  await page.goto(`/services/${listing.id}`);
  await expect(page.getByRole('heading', { name: 'Service Not Found' })).toBeVisible();
});
